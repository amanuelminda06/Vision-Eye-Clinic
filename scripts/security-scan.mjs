/**
 * Security review generator.
 *
 *   npm run security:scan
 *
 * Statically scans every server action (`'use server'`) and API route handler
 * for its authorization guard, resolves role constants from each module's
 * `roles.ts`, and writes `docs/security-review.md`:
 *   - one row per guarded endpoint (roles + guard kind)
 *   - the public/allow-listed endpoints (no session by design)
 *   - any endpoint where no guard was detected (needs manual review)
 *
 * It is a review aid, not a proof — the runtime guards remain the source of
 * truth. Re-run after adding routes/actions.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const SRC = join(ROOT, 'src');

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      if (entry === 'node_modules' || entry === '.next') continue;
      walk(full, files);
    } else if (/\.(ts|tsx)$/.test(entry) && !/\.test\.(ts|tsx)$/.test(entry)) {
      files.push(full);
    }
  }
  return files;
}

// ── role constants ──────────────────────────────────────────────────────────
const consts = new Map();
const CONST_RE = /export const ([A-Z0-9_]+)\s*(?::[^=]+)?=\s*\[([^\]]*)\]/g;
for (const file of walk(SRC)) {
  if (!file.endsWith('roles.ts')) continue;
  const source = readFileSync(file, 'utf8');
  for (const m of source.matchAll(CONST_RE)) {
    const roles = [...m[2].matchAll(/'([A-Z]+)'/g)].map((r) => r[1]);
    consts.set(m[1], roles);
  }
}

function resolveRoles(token, localConsts) {
  token = token.trim();
  const arrayMatch = token.match(/^\[([^\]]*)\]$/);
  if (!arrayMatch) return consts.get(token) ?? null;
  const inner = arrayMatch[1];
  let roles = [...inner.matchAll(/'([A-Z]+)'/g)].map((r) => r[1]);
  for (const spread of inner.matchAll(/\.\.\.\s*([A-Z0-9_]+)/g)) {
    const resolved = localConsts.get(spread[1]) ?? consts.get(spread[1]);
    if (resolved) roles = roles.concat(resolved);
  }
  return roles.length ? roles : null;
}

// ── guard detection ─────────────────────────────────────────────────────────
const PUBLIC_PREFIXES = [
  'src/app/api/public/',
  'src/app/api/auth/',
  'src/app/api/uploads/',
];
const TOKEN_GUARDS = ['CRON_SECRET'];
const LOCAL_CONST_RE = /const ([A-Z0-9_]+)\s*(?::[^=]+)?=\s*\[([^\]]*)\]/g;

function guardFor(file, source) {
  // Role arrays declared inline in the same file (e.g. const SEARCH_ROLES = [...]).
  const localConsts = new Map();
  for (const m of source.matchAll(LOCAL_CONST_RE)) {
    localConsts.set(m[1], [...m[2].matchAll(/'([A-Z]+)'/g)].map((r) => r[1]));
  }

  // withAuth(ROLES, handler) / withAuth<T>(ROLES, …) / requireRole(ROLES) / requirePageRole(ROLES)
  const callRe =
    /(withAuth(?:<[^>]*>)?|requireRole|requirePageRole)\s*\(\s*(\[[^\]]*\]|[A-Z0-9_]+)/g;
  for (const m of source.matchAll(callRe)) {
    const roles = resolveRoles(m[2], localConsts);
    if (roles) return { kind: m[1].replace(/<.*>/, ''), roles };
  }
  if (/\brequireAuth\s*\(/.test(source)) return { kind: 'requireAuth', roles: ['ANY (session)'] };
  if (/\bauth\s*\(/.test(source)) return { kind: 'auth()', roles: ['ANY (session)'] };
  if (TOKEN_GUARDS.some((token) => source.includes(token))) {
    return { kind: 'cron secret', roles: ['CRON'] };
  }
  return null;
}

function endpointKind(file) {
  if (file.endsWith('roles.ts')) return null;
  const source = readFileSync(file, 'utf8');
  const isAction = /^['"]use server['"]/.test(source.trimStart()) && /export async function/.test(source);
  const isRoute = /route\.ts$/.test(file) || file.endsWith('route.tsx');
  if (!isAction && !isRoute) return null;
  return { source, isAction, isRoute };
}

const rows = [];
const unguarded = [];
const isPublic = (rel) => PUBLIC_PREFIXES.some((p) => rel.startsWith(p));

for (const file of walk(SRC)) {
  const rel = relative(ROOT, file);
  const kind = endpointKind(file);
  if (!kind) continue;
  const guard = guardFor(file, kind.source);
  if (guard) {
    rows.push({ rel, ...guard, public: false });
  } else if (isPublic(rel)) {
    rows.push({ rel, kind: 'public (by design)', roles: ['—'], public: true });
  } else {
    unguarded.push(rel);
  }
}

rows.sort((a, b) => a.rel.localeCompare(b.rel));

const lines = [];
lines.push('# Security review');
lines.push('');
lines.push(`_Generated by \`npm run security:scan\` on ${new Date().toISOString().slice(0, 10)}._`);
lines.push('');
lines.push('Role constants live in each module\'s `roles.ts`; page/action/route guards call');
lines.push('`requirePageRole`, `requireRole` or `withAuth` with those constants. This table is a');
lines.push('static summary — the runtime guards are authoritative. Regenerate after adding endpoints.');
lines.push('');
lines.push('## Endpoints & guards');
lines.push('');
lines.push('| Endpoint / action | Guard | Roles |');
lines.push('| --- | --- | --- |');
for (const row of rows) {
  const roles = row.roles.join(', ');
  const guard = row.public ? 'public' : `\`${row.kind}\``;
  lines.push(`| \`${row.rel}\` | ${guard} | ${roles} |`);
}
lines.push('');
lines.push('## Allow-listed (no session by design)');
lines.push('');
lines.push('- `src/app/api/public/**` — public website (doctors list, booking request, photos).');
lines.push('- `src/app/api/auth/**` — NextAuth sign-in/out.');
lines.push('- `src/app/api/uploads/**` — uploaded images, key-gated.');
lines.push('- `src/app/api/jobs/**` — scheduled jobs, `Authorization: Bearer $CRON_SECRET`.');
lines.push('');
lines.push('## Needs manual review');
lines.push('');
if (unguarded.length === 0) {
  lines.push('_None — every scanned endpoint has a detected guard._');
} else {
  for (const rel of unguarded) lines.push(`- \`${rel}\``);
}
lines.push('');
lines.push('## Role capability summary');
lines.push('');
lines.push('| Constant | Roles |');
lines.push('| --- | --- |');
for (const [name, roles] of [...consts].sort((a, b) => a[0].localeCompare(b[0]))) {
  lines.push(`| \`${name}\` | ${roles.join(', ')} |`);
}
lines.push('');

const outDir = join(ROOT, 'docs');
mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, 'security-review.md');
writeFileSync(outFile, lines.join('\n'));

console.log(`✓ wrote ${relative(ROOT, outFile)} (${rows.length} guarded, ${unguarded.length} unguarded, ${consts.size} role constants)`);
if (unguarded.length) {
  console.log('  review:', unguarded.join(', '));
}