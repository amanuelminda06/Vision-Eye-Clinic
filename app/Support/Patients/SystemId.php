<?php

declare(strict_types=1);

namespace App\Support\Patients;

use App\Models\Patient;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Facades\DB;

/**
 * Generates auto-incrementing 2-letter + 4-digit system IDs.
 *
 * Sequence: AA0001 .. AA9999, AB0001 .. AB9999, ... AZ9999,
 *           BA0001 .. BZ9999, ... ZZ9999.
 *
 * The letters use A-Z (26 letters), giving 26*26 = 676 letter pairs.
 * Each pair has 9999 numbers, for a total capacity of ~6.76 million IDs.
 *
 * This is deliberately separate from the optional, manually entered
 * "Clinic ID" stored in `patients.id_no`. The system ID lives in
 * `patients.system_id` and is always generated by the application.
 */
final class SystemId
{
    /** The column that stores the auto-generated system ID. */
    public const COLUMN = 'system_id';

    /** The regex pattern for validation (2 uppercase letters + 4 digits). */
    public const PATTERN = '/^[A-Z]{2}\d{4}$/';

    /** The very first ID in the sequence. */
    public const FIRST = 'AA0001';

    /** Maximum numeric suffix per letter pair. */
    private const MAX_NUMBER = 9999;

    /** How many times to retry when a concurrent insert steals the ID. */
    private const MAX_CREATE_ATTEMPTS = 5;

    /**
     * Generate the next available system ID.
     *
     * Finds the highest existing system ID in the database and returns the
     * next one. The unique index on `system_id` is the real guarantee against
     * duplicates; `createPatient()` retries if two requests race.
     */
    public static function generateNext(): string
    {
        $lastId = self::fetchLastSystemId();

        if ($lastId === null) {
            return self::FIRST;
        }

        return self::next($lastId);
    }

    /**
     * Create a patient with the next generated system ID.
     *
     * Retries when a concurrent insert grabs the same ID first. Any other
     * unique violation (e.g. a duplicate phone) is re-thrown so the caller can
     * keep its existing duplicate handling.
     *
     * @param  array<string, mixed>  $attributes
     */
    public static function createPatient(array $attributes): Patient
    {
        for ($attempt = 1; $attempt <= self::MAX_CREATE_ATTEMPTS; $attempt++) {
            $attributes[self::COLUMN] = self::generateNext();

            try {
                return Patient::create($attributes);
            } catch (UniqueConstraintViolationException $exception) {
                if ($attempt === self::MAX_CREATE_ATTEMPTS || ! self::isSystemIdCollision($exception)) {
                    throw $exception;
                }
            }
        }

        // Unreachable: the loop either returns or throws.
        throw new \RuntimeException('Unable to allocate a system ID.');
    }

    /** The first ID in the sequence (AA0001). */
    public static function first(): string
    {
        return self::FIRST;
    }

    /**
     * Increment a system ID to the next value.
     *
     * @param  string  $currentId  Current ID in format XX0000
     * @return string Next ID in sequence
     */
    public static function next(string $currentId): string
    {
        $letters = substr($currentId, 0, 2);
        $number = (int) substr($currentId, 2, 4);

        if ($number < self::MAX_NUMBER) {
            return $letters.str_pad((string) ($number + 1), 4, '0', STR_PAD_LEFT);
        }

        // Number overflow: increment the letter pair
        return self::incrementLetters($letters).'0001';
    }

    /**
     * Increment a 2-letter code (AA -> AB -> ... -> AZ -> BA -> ... -> ZZ).
     *
     * @param  string  $letters  Two uppercase letters
     * @return string Next letter pair
     */
    private static function incrementLetters(string $letters): string
    {
        $first = ord($letters[0]);
        $second = ord($letters[1]);

        if ($second < ord('Z')) {
            return chr($first).chr($second + 1);
        }

        // Second letter overflow (e.g., AZ -> BA)
        if ($first < ord('Z')) {
            return chr($first + 1).'A';
        }

        // Both at Z (ZZ): the ~6.76M capacity is exhausted. Wrap to AA; the
        // unique index will then surface the collision instead of silently
        // overwriting data.
        return 'AA';
    }

    /** Validate a system ID format. */
    public static function isValid(string $id): bool
    {
        return (bool) preg_match(self::PATTERN, $id);
    }

    /**
     * Parse a system ID into its components.
     *
     * @return array{letters: string, number: int}
     */
    public static function parse(string $id): array
    {
        if (! self::isValid($id)) {
            throw new \InvalidArgumentException("Invalid system ID format: {$id}");
        }

        return [
            'letters' => substr($id, 0, 2),
            'number' => (int) substr($id, 2, 4),
        ];
    }

    /** Fetch the highest existing system ID using portable SQL. */
    private static function fetchLastSystemId(): ?string
    {
        $driver = DB::connection()->getDriverName();

        $query = Patient::query()->whereNotNull(self::COLUMN);

        if ($driver === 'mysql') {
            $query->where(self::COLUMN, 'REGEXP', '^[A-Z]{2}[0-9]{4}$');
            $query->orderByRaw('CAST(SUBSTRING(`system_id`, 3) AS UNSIGNED) DESC');
            $query->orderByRaw('SUBSTRING(`system_id`, 1, 2) DESC');
        } elseif ($driver === 'pgsql') {
            $query->where(self::COLUMN, '~', '^[A-Z]{2}[0-9]{4}$');
            $query->orderByRaw('CAST(SUBSTRING(system_id, 3) AS INTEGER) DESC');
            $query->orderByRaw('SUBSTRING(system_id, 1, 2) DESC');
        } else {
            // SQLite (tests): GLOB is case-sensitive and supports ranges.
            // Laravel's where() does not know GLOB as an operator, so it has
            // to be written as raw SQL or it becomes `system_id = 'GLOB'`.
            $query->whereRaw(self::COLUMN.' GLOB ?', ['[A-Z][A-Z][0-9][0-9][0-9][0-9]']);
            $query->orderByRaw('CAST(substr(`system_id`, 3) AS INTEGER) DESC');
            $query->orderByRaw('substr(`system_id`, 1, 2) DESC');
        }

        return $query->value(self::COLUMN);
    }

    /** True when the underlying unique violation is on the system_id column. */
    private static function isSystemIdCollision(UniqueConstraintViolationException $exception): bool
    {
        return str_contains($exception->getMessage(), self::COLUMN);
    }
}
